import assert from 'node:assert/strict';
import fs from 'node:fs';
import { uniqueById, groupByCause, readAs } from '../src/lib/kb/causes.ts';
const base = new URL('../src/lib/data/', import.meta.url);
const read = file => JSON.parse(fs.readFileSync(new URL(file, base), 'utf8'));
const raw = read('reports-4471.json');
const tenants = fs.readdirSync(new URL('tenants/', base)).map(f => read('tenants/' + f));
const tenantOf = r => tenants.find(t => t.handle === r.tenant);
const merged = uniqueById(raw).filter(r => r.mergedInto === 4471);
const groups = groupByCause(merged, tenantOf);
assert.equal(raw.length, 427);
assert.equal(merged.length, 412);
assert.deepEqual(groups.map(g => [g.cause, g.reports.length]), [['parser',379],['hint',33]]);
assert.equal(readAs(groups[0], read('desk-notes.json').oneDayMove), 5);
assert.equal(groups.reduce((sum,g) => sum + g.reports.length, 0), merged.length);
assert.equal(uniqueById([...raw,...raw]).length, merged.length);
const browserChanged = merged.map(r => ({...r, meta:{browserLocale:'en-US',intakeTag:'other'}}));
assert.deepEqual(groupByCause(browserChanged, tenantOf).map(g=>[g.cause,g.reports.length]), groups.map(g=>[g.cause,g.reports.length]));
console.log('PASS: 427 rows → 412 unique reports = parser 379 + hint 33; five one-day notes remain under parser.');
